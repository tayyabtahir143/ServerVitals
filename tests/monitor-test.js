import {parseTempLine,parseGpuLine,parseSampleLine,computeSample,buildRemoteScript} from '../server-vitals@tayyabtahir/collector.js';
import * as C from '../server-vitals@tayyabtahir/common.js';
function ok(value, label) { if (!value) throw Error(label); print(`ok ${label}`); }
const history = C.MonitorHistory ? new C.MonitorHistory() : null;
ok(history, 'bounded monitor history');
for (let t=0; t<=1800; t+=30)
    history.add({uptime:t, rxRate:10, txRate:20, diskFree:10000-t}, 'eth0');
ok(history.graph('rxRate').length === 30 && !history.graph('rxRate').includes('·'), '30 half-minute buckets');
ok(history.runway() === 8200, 'disk runway after sustained decline');
history.add({uptime:1801,rxRate:null,txRate:null,diskFree:8199}, 'wg0');
ok(!history.graph('rxRate').replaceAll('·',''), 'no previous interface traffic');
const alert = C.SustainedAlert && new C.SustainedAlert();
ok(alert, 'sustained alert tracker');
ok([0,15,30,31,32,33].map((t,i)=>alert.update(t,i<4,false)).join(',') === ',,warning,,recovered,', 'one warning and recovery');
ok([40,75,80].every(t=>!alert.update(t,true,true)), 'maintenance mute');
const options = {mount:'/srv/data', favorites:['veth3'], labels:{veth3:'cache'}, maintenance:true};
const host = C.normalizeServer({host:'a.invalid', id:'a', ...options}).server;
ok(Object.keys(options).every(k => JSON.stringify(host[k]) === JSON.stringify(options[k])), 'per-host options round trip');
ok(!C.validMount('/a;date') && !C.validMount('relative') && C.validMount('/srv/volume one'), 'mount allowlist');
const raw = n => parseSampleLine(`SV4 eth0 ${n} 1 1 1 100 80 9 2 1 300 180 100 eth0 3 4 ${n} 2`);
ok(raw(1) && computeSample(raw(1),raw(2),'eth0').dropping === true, 'selected drop increases');
ok(computeSample(null,raw(1),'eth0').diskFree === 102400, 'available not total minus used');
ok(buildRemoteScript(5,'/srv/volume one').includes("df -kP '/srv/volume one'"), 'quoted mount');
ok(!buildRemoteScript(5,'/a;date').includes('/a;date'), 'invalid mount never in script');
const five = parseSampleLine('SV5 eth0 9 1 1 1 100 80 9 2 1 300 180 100 20 30 50 10 eth0 3 4 0 0');
const detail = computeSample(null, five, 'eth0');
ok(detail.memFree === 20480 && detail.memCached === 30720 && detail.swapUsed === 40960, 'memory detail fields');
ok(computeSample(null, raw(1), 'eth0').memFree === null, 'older sampler lines still parse');
const six = parseSampleLine('SV6 eth0 9 1 1 1 100 80 9 2 1 300 180 100 20 30 50 10 2 / 300 180 100 /data 5000 2000 3000 eth0 3 4 0 0');
const disks = computeSample(null, six, 'eth0').disks;
ok(disks.length === 2 && disks[1].mount === '/data' && disks[1].percent === 40 && disks[1].free === 3072000, 'every disk is reported');
ok(parseSampleLine('SV6 eth0 9 1 1 1 100 80 9 2 1 300 180 100 20 30 50 10 0 eth0 3 4 0 0').disks.length === 0, 'no extra disks');
ok(!parseSampleLine('SV6 eth0 9 1 1 1 100 80 9 2 1 300 180 100 20 30 50 10 2 / 300 180 100 eth0 3 4 0 0'), 'short disk list refused');
const temp = parseTempLine('SVT 45500 coretemp Package id 0');
ok(temp.label === 'coretemp Package id 0' && temp.celsius === 45.5, 'temperature line');
ok(!parseTempLine('SVT 999000 broken temp1') && !parseTempLine('SVT x y'), 'implausible temperature refused');
const gpu = parseGpuLine('SVG 37, 1024, 8192, 60, [N/A], 55.20, NVIDIA RTX A1000, Laptop');
ok(gpu.name === 'NVIDIA RTX A1000, Laptop' && gpu.usage === 37 && gpu.memTotal === 8192 * 1048576 && gpu.fan === null && gpu.power === 55.2, 'graphics card line');
ok(!parseGpuLine('SVG 1, 2'), 'short graphics line refused');
six.temps = [temp, temp];
ok(computeSample(null, six, 'eth0').temps.map(t => t.label).join() === 'coretemp Package id 0,coretemp Package id 0 2', 'duplicate sensor labels kept apart');
